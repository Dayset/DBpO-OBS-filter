#!/usr/bin/env python3
"""Builds the phone versions of DBpO Unsquish from the extension's own files.

  build.py            writes ../userscript/dbpo-unsquish.user.js (one file for a userscript
                      manager: Userscripts / Tampermonkey / Violentmonkey, Safari on iPhone,
                      any Android browser that has one)
  build.py --firefox  also writes dist/dbpo-unsquish-firefox.zip (Firefox for Android,
                      install from a file or sideload; needs signing for release builds)
  build.py --check    fails if the committed userscript is out of date (for CI)

The userscript is the real content.js, chatsignal.js, squish.js and starvation.js plus a small shim that
maps chrome.storage onto the userscript manager's storage, and the popup turned into a
floating settings panel (button in the corner of the page).
"""
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "userscript", "dbpo-unsquish.user.js")
VERSION = re.search(r'"version":\s*"([^"]+)"', open(os.path.join(HERE, "manifest.json")).read()).group(1)


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


HEADER = f"""// ==UserScript==
// @name         DBpO Unsquish
// @namespace    https://github.com/Dayset/DBpO-OBS-filter
// @version      {VERSION}
// @description  Unfolds Foveated Squish streams (sharp center, squeezed edges) with a GPU shader. Phone/userscript build.
// @match        https://www.twitch.tv/*
// @match        https://m.twitch.tv/*
// @run-at       document-idle
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM.getValue
// @grant        GM.setValue
// ==/UserScript==
// Generated by viewer/unsquish-extension/build.py from the extension sources. Edit those, not this.
// Only runs on the @match pages above. To use it on another site, add an @match line (your
// userscript manager can also do this per site).
"""

SHIM = r"""
/* chrome.storage on top of the userscript manager's storage (sync and local share one store). */
const chrome = (() => {
	const NS = "dbpoUnsquish:";
	const listeners = [];
	const readAll = (area) => {
		try {
			const raw = typeof GM_getValue === "function" ? GM_getValue(NS + area, "{}") : localStorage.getItem(NS + area) || "{}";
			return JSON.parse(raw) || {};
		} catch (e) {
			return {};
		}
	};
	const writeAll = (area, obj) => {
		const raw = JSON.stringify(obj);
		try {
			if (typeof GM_setValue === "function") GM_setValue(NS + area, raw);
			else localStorage.setItem(NS + area, raw);
		} catch (e) {}
	};
	const store = (area) => ({
		get(defaults, cb) {
			const have = readAll(area);
			const out = { ...(defaults || {}) };
			for (const k of Object.keys(out)) if (k in have) out[k] = have[k];
			cb(out);
		},
		set(obj, cb) {
			const have = readAll(area);
			const changes = {};
			for (const [k, v] of Object.entries(obj)) {
				changes[k] = { oldValue: have[k], newValue: v };
				have[k] = v;
			}
			writeAll(area, have);
			for (const l of listeners) l(changes, area);
			if (cb) cb();
		},
	});
	return { storage: { sync: store("sync"), local: store("local"), onChanged: { addListener: (f) => listeners.push(f) } } };
})();
"""

PANEL = r"""
/* Floating settings panel (the extension's popup, in a shadow root). */
(() => {
	if (window !== window.top) return;
	const host = document.createElement("div");
	host.style.cssText = "position:fixed;z-index:2147483647;left:8px;bottom:8px;font:14px system-ui,sans-serif";
	const root = host.attachShadow({ mode: "open" });
	root.innerHTML = `<style>
		button.gear{width:36px;height:36px;border-radius:18px;border:0;background:#772ce8;color:#fff;font-size:18px;opacity:.55}
		#box{display:none;max-height:80vh;overflow:auto;background:#fff;color:#1d1d1f;border-radius:10px;padding:8px;box-shadow:0 4px 18px #0006;margin-bottom:6px}
		#box.open{display:block}
		${POPUP_STYLE}
		body,#box{width:min(320px,88vw)}
	</style><div id="box">${POPUP_BODY}</div><button class="gear" id="gear" aria-label="DBpO Unsquish settings">◐</button>`;
	root.getElementById("gear").onclick = () => root.getElementById("box").classList.toggle("open");
	document.documentElement.appendChild(host);
	window.__dbpoPanel = root;
})();
"""


def popup_parts():
    html = read("popup.html")
    style = re.search(r"<style>(.*?)</style>", html, re.S).group(1)
    style = re.sub(r"body \{[^}]*\}", "", style, count=1)  # panel supplies its own body box
    body = re.search(r"<body>(.*?)<script", html, re.S).group(1)
    return style, body


def build_userscript():
    style, body = popup_parts()
    panel = PANEL.replace("${POPUP_STYLE}", style.replace("`", "\\`")).replace("${POPUP_BODY}", body.replace("`", "\\`"))
    popup_js = read("popup.js").replace(
        "const $ = (id) => document.getElementById(id);", "const $ = (id) => window.__dbpoPanel.getElementById(id);", 1)
    assert "__dbpoPanel" in popup_js
    parts = [
        HEADER,
        "(function () {\n\"use strict\";\n",
        SHIM,
        "{\n" + read("squish.js") + "\n}\n",
        "{\n" + read("starvation.js") + "\n}\n",
        panel,
        "{\n" + popup_js + "\n}\n",
        "{\n" + read("chatsignal.js") + "\n}\n",
        "{\n" + read("content.js") + "\n}\n",
        "})();\n",
    ]
    return "\n".join(parts)


def build_firefox():
    dist = os.path.join(HERE, "dist")
    os.makedirs(dist, exist_ok=True)
    path = os.path.join(dist, "dbpo-unsquish-firefox.zip")
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(HERE, "manifest.firefox.json"), "manifest.json")
        for n in ("squish.js", "starvation.js", "content.js", "chatsignal.js", "popup.html", "popup.js"):
            z.write(os.path.join(HERE, n), n)
        for n in os.listdir(os.path.join(HERE, "icons")):
            z.write(os.path.join(HERE, "icons", n), "icons/" + n)
    return path


def main():
    text = build_userscript()
    out = os.path.normpath(OUT)
    if "--check" in sys.argv:
        have = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
        if have != text:
            print("userscript is out of date: run viewer/unsquish-extension/build.py")
            sys.exit(1)
        print("userscript up to date")
        return
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", out, f"({len(text) // 1024} KB)")
    if "--firefox" in sys.argv:
        print("wrote", build_firefox())


if __name__ == "__main__":
    main()
