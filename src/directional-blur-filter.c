	float object_trust; /* 0 while motion is beyond what image analysis can measure */
	bool last_fit_ok;
	bool last_ready;
	uint64_t log_counter;

	int cur; /* index into small[] holding the newest frame */
	bool have_prev;
	bool needs_update;
	bool output_valid;

	uint32_t width, height;
	uint32_t flow_w, flow_h;

	struct camera_model camera; /* smoothed camera motion, px/frame */

	/* settings */
	float strength; /* object blur strength */
	bool camera_enabled;
	float camera_strength;
	float camera_smoothing;
	float object_threshold;
	float max_radius;
	int downscale;
	int search_radius;
	float sensitivity;
	int coherence_radius;
	float min_motion;
	float static_bias;
	int samples;
	enum view_mode view;
	int lookahead;
