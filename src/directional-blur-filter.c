static bool lookahead_modified(obs_properties_t *props, obs_property_t *p, obs_data_t *settings)
{
	UNUSED_PARAMETER(p);
	obs_property_t *info = obs_properties_get(props, S_LOOKAHEAD_INFO);
	if (!info)
		return false;

	int frames = (int)obs_data_get_int(settings, S_LOOKAHEAD);
	struct obs_video_info ovi;
	double fps = 60.0;
	if (obs_get_video_info(&ovi) && ovi.fps_den)
		fps = (double)ovi.fps_num / (double)ovi.fps_den;

	char text[256];
	if (frames <= 0)
		snprintf(text, sizeof(text), "%s", T("LookAheadInfo.Off"));
	else
		snprintf(text, sizeof(text), T("LookAheadInfo.On"), frames, 1000.0 * frames / fps, fps);
	obs_property_set_description(info, text);
	return true;
}

