static void dob_update(void *data, obs_data_t *settings)
{
	struct dob_filter *f = data;
	int old_downscale = f->downscale;

	f->strength = (float)obs_data_get_double(settings, S_STRENGTH);
	f->max_radius = (float)obs_data_get_double(settings, S_MAX_RADIUS);
	f->downscale = (int)obs_data_get_int(settings, S_DOWNSCALE);
	f->search_radius = (int)obs_data_get_int(settings, S_SEARCH);
	f->sensitivity = (float)obs_data_get_double(settings, S_SENSITIVITY);
	f->coherence_radius = (int)obs_data_get_int(settings, S_COHERENCE);
	f->min_motion = (float)obs_data_get_double(settings, S_MIN_MOTION);
	f->static_bias = (float)obs_data_get_double(settings, S_STATIC_BIAS);
	f->samples = (int)obs_data_get_int(settings, S_SAMPLES);
	f->view = (enum view_mode)obs_data_get_int(settings, S_VIEW);
	f->camera_enabled = obs_data_get_bool(settings, S_CAMERA);
	f->camera_strength = (float)obs_data_get_double(settings, S_CAMERA_STRENGTH);
	f->camera_smoothing = (float)obs_data_get_double(settings, S_CAMERA_SMOOTHING);
	f->object_threshold = (float)obs_data_get_double(settings, S_OBJECT_THRESHOLD);
	f->lookahead = (int)obs_data_get_int(settings, S_LOOKAHEAD);
	if (f->lookahead < 0)
		f->lookahead = 0;
	if (f->lookahead > MAX_LOOKAHEAD)
		f->lookahead = MAX_LOOKAHEAD;
	f->clear_shape = (enum clear_shape)obs_data_get_int(settings, S_CLEAR_SHAPE);
	f->clear_size = (float)obs_data_get_double(settings, S_CLEAR_SIZE) / 100.0f;
	f->clear_feather = (float)obs_data_get_double(settings, S_CLEAR_FEATHER) / 100.0f;
	f->opacity = (float)obs_data_get_double(settings, S_OPACITY) / 100.0f;
	f->object_blur = (enum object_blur_type)obs_data_get_int(settings, S_OBJECT_BLUR_TYPE);
	f->area_strength = (float)obs_data_get_double(settings, S_AREA_STRENGTH);
	f->glow_amount = (float)obs_data_get_double(settings, S_GLOW) / 100.0f;
	f->glow_radius = (float)obs_data_get_double(settings, S_GLOW_RADIUS);
	f->trails = (enum trail_mode)obs_data_get_int(settings, S_TRAILS);
	/* Trail length (0..100) -> per-frame persistence (0..0.97). */
	f->trail_persistence = 0.97f * (float)obs_data_get_double(settings, S_TRAIL_LENGTH) / 100.0f;
	f->dither = obs_data_get_bool(settings, S_DITHER);
	f->mouse_enabled = obs_data_get_bool(settings, S_MOUSE);
	f->mouse_mode = (enum mouse_mode)obs_data_get_int(settings, S_MOUSE_MODE);
	f->mouse_auto = obs_data_get_int(settings, S_MOUSE_CAL) == 0;
	f->mouse_gain[0] = (float)obs_data_get_double(settings, S_MOUSE_GAIN_X);
	f->mouse_gain[1] = (float)obs_data_get_double(settings, S_MOUSE_GAIN_Y);
	f->mouse_lag = (int)obs_data_get_int(settings, S_MOUSE_LAG);
	if (f->mouse_lag < 0)
		f->mouse_lag = 0;
	if (f->mouse_lag > MOUSE_MAX_LAG)
		f->mouse_lag = MOUSE_MAX_LAG;

	/* UI detection sensitivity: higher tolerates more change and needs
	 * fewer unchanged frames before a region counts as UI. */
	f->ui_enabled = obs_data_get_bool(settings, S_UI);
	const float us = (float)obs_data_get_double(settings, S_UI_SENS) / 100.0f;
	f->ui_threshold = 0.004f + 0.06f * us;
	f->ui_rise = 1.0f / (90.0f - 80.0f * us);
	f->ui_margin_px = (int)obs_data_get_int(settings, S_UI_MARGIN);
	f->cam_speed_min = (float)obs_data_get_double(settings, S_CAM_SPEED_MIN);
	f->cam_speed_full = (float)obs_data_get_double(settings, S_CAM_SPEED_FULL);
	f->cam_curve = (float)obs_data_get_double(settings, S_CAM_CURVE);

	if (f->downscale < 1)
		f->downscale = 4;

	/* A new flow resolution invalidates the previous frame. */
	if (old_downscale != f->downscale)
		f->have_prev = false;
}

static void *dob_create(obs_data_t *settings, obs_source_t *context)
{
	struct dob_filter *f = bzalloc(sizeof(*f));
	f->context = context;

	/* Prefer the shader in the data folder (handy for live tweaking);
	 * fall back to the copy compiled into the DLL so a missing or
	 * misplaced data folder can't stop the filter from starting. */
	char *path = obs_module_file("directional_object_blur.effect");
	obs_enter_graphics();
	char *errors = NULL;
	if (path) {
		f->effect = gs_effect_create_from_file(path, &errors);
		if (!f->effect)
			obs_log(LOG_WARNING, "shader file '%s' failed to compile, using built-in copy: %s", path,
				errors ? errors : "(no details)");
		bfree(errors);
		errors = NULL;
	} else {
		obs_log(LOG_INFO, "data folder not found, using built-in shader");
	}
	if (!f->effect) {
		f->effect = gs_effect_create(dob_embedded_effect, "directional_object_blur.effect", &errors);
		if (!f->effect)
			obs_log(LOG_ERROR, "built-in shader failed to compile: %s", errors ? errors : "(no details)");
		bfree(errors);
	}
	create_textures(f);
	obs_leave_graphics();
	bfree(path);

	if (!f->effect) {
		obs_enter_graphics();
		free_textures(f);
		obs_leave_graphics();
		bfree(f);
		return NULL;
	}

	f->agree = 0.0f; /* the mouse must agree with the picture before it is used */
	f->object_trust = 1.0f;
	mouse_sync_reset(&f->sync);
	for (int i = 0; i < CAM_HIST; i++)
		f->mouse_hist_frame[i] = -1;

	dob_update(f, settings);
	return f;
}

static void dob_destroy(void *data)
{
	struct dob_filter *f = data;
	if (f->mouse_ref)
		raw_mouse_release();
	obs_enter_graphics();
	free_textures(f);
	gs_effect_destroy(f->effect);
	obs_leave_graphics();
	bfree(f);
}

static void dob_tick(void *data, float seconds)
{
	UNUSED_PARAMETER(seconds);
	struct dob_filter *f = data;

	/* The previous frame was never rendered (scene not visible): its mouse
	 * movement would otherwise pile up and land on one frame later. */
	if (f->needs_update)
		f->mouse_pending[0] = f->mouse_pending[1] = 0.0f;
	/* video_render can run several times per frame (preview, program,
	 * projectors). Only advance the motion history once per frame. */
	f->needs_update = true;

	/* Raw mouse: start/stop the shared listener here (one thread for all
	 * instances) and accumulate movement since the last processed frame. */
	if (f->mouse_enabled && !f->mouse_ref) {
		f->mouse_ok = raw_mouse_acquire();
		f->mouse_ref = true;
		raw_mouse_read_totals(&f->mouse_last[0], &f->mouse_last[1]);
		f->mouse_pending[0] = f->mouse_pending[1] = 0.0f;
	} else if (!f->mouse_enabled && f->mouse_ref) {
		raw_mouse_release();
		f->mouse_ref = f->mouse_ok = false;
	}
	if (f->mouse_ok) {
		uint32_t now[2];
		raw_mouse_read_totals(&now[0], &now[1]);
		for (int a = 0; a < 2; a++) {
			f->mouse_pending[a] += (float)(int32_t)(now[a] - f->mouse_last[a]);
			f->mouse_last[a] = now[a];
		}
	}
}

/* ------------------------------------------------------------------ rendering */

static inline int ring_idx(const struct dob_filter *f, uint64_t n)
{
	return (int)(n % (uint64_t)f->ring_size);
}

/* Sizes the frame/motion rings to lookahead + 1, freeing unused slots so a
 * filter without look-ahead holds only one full-res frame. */
static void ensure_rings(struct dob_filter *f)
{
	int want = f->lookahead + 1;
	if (want == f->ring_size)
		return;
	for (int i = 0; i < RING_MAX; i++) {
		if (i < want) {
			if (!f->frames[i])
				f->frames[i] = gs_texrender_create(GS_RGBA, GS_ZS_NONE);
			if (!f->coh_ring[i])
				f->coh_ring[i] = gs_texrender_create(GS_RGBA16F, GS_ZS_NONE);
		} else {
			gs_texrender_destroy(f->frames[i]);
			gs_texrender_destroy(f->coh_ring[i]);
			f->frames[i] = f->coh_ring[i] = NULL;
		}
	}
	f->ring_size = want;
	f->have_prev = false;
}

static bool capture_input(struct dob_filter *f, gs_texrender_t *dst, obs_source_t *target, obs_source_t *parent)
{
	gs_texrender_reset(dst);
	if (!gs_texrender_begin(dst, f->width, f->height))
		return false;

	struct vec4 clear;
	vec4_zero(&clear);
	gs_clear(GS_CLEAR_COLOR, &clear, 0.0f, 0);
	gs_ortho(0.0f, (float)f->width, 0.0f, (float)f->height, -100.0f, 100.0f);

	uint32_t flags = obs_source_get_output_flags(target);
	bool custom_draw = (flags & OBS_SOURCE_CUSTOM_DRAW) != 0;
	bool async = (flags & OBS_SOURCE_ASYNC) != 0;

	if (target == parent && !custom_draw && !async)
		obs_source_default_render(target);
	else
		obs_source_video_render(target);

	gs_texrender_end(dst);
	return true;
}

static void store_camera(struct dob_filter *f, uint64_t frame, const struct camera_model *m)
{
	int i = (int)(frame % CAM_HIST);
	f->cam_hist[i] = *m;
	f->cam_hist_frame[i] = (int64_t)frame;
}

static const struct camera_model *get_camera(const struct dob_filter *f, uint64_t frame)
{
	int i = (int)(frame % CAM_HIST);
	return f->cam_hist_frame[i] == (int64_t)frame ? &f->cam_hist[i] : NULL;
}

/* Fits the camera model for the newest frame's motion. The GPU copy is read
 * back one frame later so the CPU never stalls; the result is filed under
 * the frame it was measured on. */
/* ------------------------------------------------------------------ mouse */

static bool mouse_counts(const struct dob_filter *f, int64_t frame, float out[2])
{
	if (frame < 0)
		return false;
	int i = (int)(frame % CAM_HIST);
	if (f->mouse_hist_frame[i] != frame)
		return false;
	out[0] = f->mouse_hist[i][0];
	out[1] = f->mouse_hist[i][1];
	return true;
}

/* Mouse calibration is usable: auto-calibrated and confident, or manual. */
static bool mouse_calibrated(const struct dob_filter *f)
{
	return f->mouse_ok && (!f->mouse_auto || f->sync.ready);
}

/* Camera pan (px) the mouse predicts for the motion into `frame`. */
static bool mouse_predict(const struct dob_filter *f, uint64_t frame, float pan[2])
{
	const int lag = f->mouse_auto ? f->sync.lag : f->mouse_lag;
	float m[2];
	if (!mouse_counts(f, (int64_t)frame - lag, m))
		return false;
	for (int a = 0; a < 2; a++)
		pan[a] = m[a] * (f->mouse_auto ? f->sync.gain[a] : f->mouse_gain[a]);
	return true;
}

static float measurable_range(const struct dob_filter *f)
{
	return 0.7f * (float)(f->search_radius * f->downscale);
}

/* Called when the camera fit for `frame` arrives: teaches the calibration
 * from trustworthy frames and tracks whether the mouse agrees with what is
 * on screen (it doesn't in menus, where the cursor moves but the view
 * doesn't). */
static void mouse_learn(struct dob_filter *f, uint64_t frame, bool fit_ok, const struct camera_model *fit, float match)
{
	if (!f->mouse_ok)
		return;
	const float range = measurable_range(f);
	const float fit_pan = hypotf(fit->x[0], fit->y[0]);

	/* Keep learning even in manual mode: the estimate is shown as a hint. */
	if (fit_ok && match > 0.6f && fit_pan < range) {
		float m[MOUSE_MAX_LAG + 1][2];
		bool valid[MOUSE_MAX_LAG + 1];
		for (int l = 0; l <= MOUSE_MAX_LAG; l++)
			valid[l] = mouse_counts(f, (int64_t)frame - l, m[l]);
		mouse_sync_observe(&f->sync, m, valid, fit->x[0], fit->y[0]);
	}

	float p[2];
	if (!mouse_calibrated(f) || !mouse_predict(f, frame, p))
		return;
	const float pred = hypotf(p[0], p[1]);
	int consistent = -1;
	if (pred > range) {
		/* A real fast turn makes the motion search fail; in a menu the
		 * static picture still matches perfectly. */
		consistent = match < 0.5f;
	} else if (fit_ok && pred > 2.0f) {
		/* The mouse moved noticeably: the picture must move the same way.
		 * (Picture moving without the mouse, e.g. strafing, says nothing.) */
		float err = hypotf(fit->x[0] - p[0], fit->y[0] - p[1]);
		consistent = err < 1.0f + 0.25f * fmaxf(pred, fit_pan);
	}
	if (consistent >= 0)
		f->agree = f->agree * 0.9f + (consistent ? 0.1f : 0.0f);
}

/* Replaces the camera pan with the mouse prediction when that is the better
 * source, for the output frame t (centered on t with look-ahead). */
static void mouse_apply(struct dob_filter *f, uint64_t t, uint64_t newest)
{
	f->object_trust = 1.0f;
	if (!mouse_calibrated(f))
		return;

	float pan[2] = {0.0f, 0.0f};
	if (f->lookahead > 0) {
		const double center = (double)t + 0.5;
		const double sigma = 0.5 + (double)f->camera_smoothing * (double)f->lookahead;
		double wsum = 0.0, acc[2] = {0.0, 0.0};
		for (uint64_t k = t; k <= newest && k <= t + 1 + (uint64_t)f->lookahead; k++) {
			float p[2];
			if (!mouse_predict(f, k, p))
				continue;
			double d = ((double)k - center) / sigma;
			double w = exp(-0.5 * d * d);
			acc[0] += w * p[0];
			acc[1] += w * p[1];
			wsum += w;
		}
		if (wsum <= 0.0)
			return;
		pan[0] = (float)(acc[0] / wsum);
		pan[1] = (float)(acc[1] / wsum);
	} else if (!mouse_predict(f, t, pan)) {
		return;
	}

	const bool beyond = hypotf(pan[0], pan[1]) > measurable_range(f);
	bool use;
	if (f->mouse_mode == MOUSE_OVERRIDE)
		use = true;
	else
		use = f->agree > 0.5f && (beyond || !f->last_fit_ok);
	if (!use)
		return;

	f->camera.x[0] = pan[0];
	f->camera.y[0] = pan[1];
	if (beyond) {
		/* Image analysis is unreliable this frame: drop its zoom/rotation
		 * terms and don't mistake the smeared image for moving objects. */
		f->camera.x[1] = f->camera.x[2] = 0.0f;
		f->camera.y[1] = f->camera.y[2] = 0.0f;
		f->object_trust = 0.0f;
	}
}

static void mouse_log(struct dob_filter *f)
{
	if (f->mouse_ok && f->sync.ready != f->last_ready) {
		f->last_ready = f->sync.ready;
		obs_source_update_properties(f->context); /* refresh the status line */
		obs_log(LOG_INFO, "mouse calibration %s", f->sync.ready ? "ready" : "lost, relearning");
	}
	if (!f->mouse_ok || ++f->log_counter % 600 != 0)
		return;
	if (f->mouse_auto)
		obs_log(LOG_INFO,
			"mouse calibration: gain x=%.3f y=%.3f px/count, latency %d frames, match %.0f%%, %s, agreement %.0f%%",
			f->sync.gain[0], f->sync.gain[1], f->sync.lag, f->sync.correlation * 100.0f,
			f->sync.ready ? "in use" : "learning", f->agree * 100.0f);
	else
		obs_log(LOG_INFO, "mouse (manual): agreement %.0f%%", f->agree * 100.0f);
}

static void update_camera_model(struct dob_filter *f, gs_texrender_t *motion, uint64_t frame)
{
	struct pass_inputs fit = {.image = motion,
				  .texel_x = 1.0f / (float)f->flow_w,
				  .texel_y = 1.0f / (float)f->flow_h};
	if (!run_pass(f, f->fit, "FitSample", FIT_W, FIT_H, &fit))
		return;

	int write = f->stage_idx;
	int read = write ^ 1;
	gs_stage_texture(f->stage[write], gs_texrender_get_texture(f->fit));
	f->stage_ready[write] = true;
	f->stage_frame[write] = frame;
	f->stage_idx = read;

	if (!f->stage_ready[read])
		return;

	uint8_t *data = NULL;
	uint32_t linesize = 0;
	if (!gs_stagesurface_map(f->stage[read], &data, &linesize))
		return;

	struct camera_model fresh;
	const size_t stride = linesize / sizeof(float);
	bool ok = camera_model_fit((const float *)data, FIT_W, FIT_H, stride, 0.1f, &fresh);
	float match = camera_match_score((const float *)data, FIT_W, FIT_H, stride);
	gs_stagesurface_unmap(f->stage[read]);
	f->match_hist[f->stage_frame[read] % CAM_HIST] = match;
	f->last_fit_ok = ok && match > 0.5f;
	mouse_learn(f, f->stage_frame[read], ok, &fresh, match);
	f->stage_ready[read] = false;

	if (!ok)
		memset(&fresh, 0, sizeof(fresh)); /* nothing reliable: treat as still */
	store_camera(f, f->stage_frame[read], &fresh);

	/* No look-ahead: exponential smoothing of the latest fit (lags slightly). */
	if (f->lookahead == 0)
		camera_model_smooth(&f->camera, &fresh, f->camera_smoothing);
}

/* With look-ahead, the camera model for output frame t is a Gaussian-weighted
 * average of the fits on both sides of it (motion into t and out of t), so it
 * is smooth without lagging behind the real camera. */
static void centered_camera(struct dob_filter *f, uint64_t t, int lookahead)
{
	const double center = (double)t + 0.5;
	const double sigma = 0.5 + (double)f->camera_smoothing * (double)lookahead;
	double wsum = 0.0, x[3] = {0}, y[3] = {0};

	int64_t lo = (int64_t)t + 1 - lookahead;
	int64_t hi = (int64_t)t + 1 + lookahead;
	for (int64_t k = lo < 0 ? 0 : lo; k <= hi; k++) {
		const struct camera_model *m = get_camera(f, (uint64_t)k);
		if (!m)
			continue;
		double d = ((double)k - center) / sigma;
		double w = exp(-0.5 * d * d);
		for (int i = 0; i < 3; i++) {
			x[i] += w * m->x[i];
			y[i] += w * m->y[i];
		}
		wsum += w;
	}
	if (wsum <= 0.0)
		return; /* keep the previous model until fits arrive */
	for (int i = 0; i < 3; i++) {
		f->camera.x[i] = (float)(x[i] / wsum);
		f->camera.y[i] = (float)(y[i] / wsum);
	}
}

static void reset_history(struct dob_filter *f)
{
	memset(&f->camera, 0, sizeof(f->camera));
	f->stage_ready[0] = f->stage_ready[1] = false;
	for (int i = 0; i < CAM_HIST; i++) {
		f->cam_hist_frame[i] = -1;
		f->mouse_hist_frame[i] = -1;
	}
	f->frame_no = 0;
	f->history_valid = false;
	f->last_fit_ok = false;
	f->ui_valid = false;
}

static void process_frame(struct dob_filter *f, obs_source_t *target, obs_source_t *parent)
{
	const float fw = (float)f->width, fh = (float)f->height;
	const float sw = (float)f->flow_w, sh = (float)f->flow_h;

	ensure_rings(f);
	if (!f->have_prev)
		reset_history(f);

	const uint64_t newest = f->frame_no;
	gs_texrender_t *frame = f->frames[ring_idx(f, newest)];
	gs_texrender_t *motion = f->coh_ring[ring_idx(f, newest)];
	if (!capture_input(f, frame, target, parent))
		return;

	f->cur ^= 1;
	gs_texrender_t *cur_small = f->small[f->cur];
	gs_texrender_t *prev_small = f->have_prev ? f->small[f->cur ^ 1] : cur_small;

	/* 1. Downsample the newest frame to flow resolution. */
	struct pass_inputs down = {.image = frame, .texel_x = 1.0f / fw, .texel_y = 1.0f / fh};
	run_pass(f, cur_small, "Downsample", f->flow_w, f->flow_h, &down);

	/* 2. Block-matching optical flow against the previous frame. */
	struct pass_inputs flow = {.image = cur_small,
				   .prev_image = prev_small,
				   .texel_x = 1.0f / sw,
				   .texel_y = 1.0f / sh};
	run_pass(f, f->flow, "Flow", f->flow_w, f->flow_h, &flow);
	f->have_prev = true;

	/* 3. Pull motion together within same-colored regions; keep it per frame. */
	struct pass_inputs coh = {.image = f->flow,
				  .color_small = cur_small,
				  .texel_x = 1.0f / sw,
				  .texel_y = 1.0f / sh};
	run_pass(f, motion, "Coherence", f->flow_w, f->flow_h, &coh);

	/* 3b. Static UI: regions that stay identical frame after frame. */
	if (f->ui_enabled) {
		const int prev = f->ui_idx, next = prev ^ 1;
		struct pass_inputs sm = {.image = cur_small,
					 .prev_image = prev_small,
					 .ui_state = f->ui_state[prev],
					 .texel_x = 1.0f / sw,
					 .texel_y = 1.0f / sh};
		struct pass_inputs dil = {.image = f->ui_state[next], .texel_x = 1.0f / sw, .texel_y = 1.0f / sh};
		if (run_pass(f, f->ui_state[next], "StaticMask", f->flow_w, f->flow_h, &sm) &&
		    run_pass(f, f->ui_mask, "UIDilate", f->flow_w, f->flow_h, &dil)) {
			f->ui_idx = next;
			f->ui_valid = true;
		}
	} else {
		f->ui_valid = false;
	}

	/* Mouse movement since the previous frame belongs to this frame. */
	{
		int i = (int)(newest % CAM_HIST);
		f->mouse_hist[i][0] = f->mouse_pending[0];
		f->mouse_hist[i][1] = f->mouse_pending[1];
		f->mouse_hist_frame[i] = (int64_t)newest;
		f->mouse_pending[0] = f->mouse_pending[1] = 0.0f;
	}

	f->frame_no++;

	/* The frame we output: `lookahead` frames behind the newest (less while
	 * the ring is still filling after a reset). */
	int la = f->lookahead;
	if ((uint64_t)la > newest)
		la = (int)newest;
	const uint64_t t = newest - (uint64_t)la;

	/* 4. Camera motion. */
	if (f->camera_enabled) {
		update_camera_model(f, motion, newest);
		if (f->lookahead > 0)
			centered_camera(f, t, f->lookahead);
	} else {
		memset(&f->camera, 0, sizeof(f->camera));
	}
	if (f->camera_enabled)
		mouse_apply(f, t, newest);
	else
		f->object_trust = 1.0f;
	mouse_log(f);

	/* 5. Split motion into camera and object parts, apply strengths. With
	 * look-ahead, also blend in the motion out of frame t (frame t + 1). */
	const bool have_next = t + 1 <= newest;
	struct pass_inputs comb = {.image = f->coh_ring[ring_idx(f, t)],
				   .motion = have_next ? f->coh_ring[ring_idx(f, t + 1)] : NULL,
				   .temporal_blend = have_next ? 1.0f : 0.0f,
				   .texel_x = 1.0f / sw,
				   .texel_y = 1.0f / sh};
	run_pass(f, f->combined, "Combine", f->flow_w, f->flow_h, &comb);

	/* 6. Neighbor max, wide enough to cover the longest allowed blur. */
	struct pass_inputs nmax = {.image = f->combined, .texel_x = 1.0f / sw, .texel_y = 1.0f / sh};
	run_pass(f, f->neighbor, "NeighborMax", f->flow_w, f->flow_h, &nmax);

	/* 7. Final gather at full resolution (or the debug view) on frame t. */
	gs_texrender_t *frame_t = f->frames[ring_idx(f, t)];
	const bool debug = f->view != VIEW_RESULT;
	struct pass_inputs blur = {.image = frame_t,
				   .motion = f->combined,
				   .motion_max = f->neighbor,
				   .texel_x = 1.0f / fw,
				   .texel_y = 1.0f / fh};
	f->output_valid = run_pass(f, f->blurred, debug ? "DebugVectors" : "Blur", f->width, f->height, &blur);
	gs_texrender_t *result = f->blurred;

	/* 8. Optional per-object effects and trails. */
	const bool fx = !debug &&
			(f->object_blur != OBJ_BLUR_DIRECTIONAL || f->glow_amount > 0.0f || f->trails != TRAILS_OFF);
	if (fx && f->output_valid) {
		const int prev = f->hist_idx, next = prev ^ 1;
		struct pass_inputs ein = {.image = f->blurred,
					  .motion = f->combined,
					  .original = frame_t,
					  .history = f->hist[prev],
					  .trail_mask = f->tmask[prev],
					  .texel_x = 1.0f / fw,
					  .texel_y = 1.0f / fh};
		bool ok = run_pass(f, f->hist[next], "Effects", f->width, f->height, &ein);
		struct pass_inputs tin = {.image = f->combined,
					  .motion = f->combined,
					  .trail_mask = f->tmask[prev],
					  .texel_x = 1.0f / sw,
					  .texel_y = 1.0f / sh};
		ok = ok && run_pass(f, f->tmask[next], "TrailMask", f->flow_w, f->flow_h, &tin);
		if (ok) {
			f->hist_idx = next;
			f->history_valid = true;
			result = f->hist[next];
		}
	} else {
		f->history_valid = false;
	}

	/* 9. Opacity: mix with the unprocessed frame. */
	if (!debug && f->opacity < 0.999f && f->output_valid) {
		struct pass_inputs pin = {.image = result,
					  .original = frame_t,
					  .texel_x = 1.0f / fw,
					  .texel_y = 1.0f / fh};
		if (run_pass(f, f->output, "Present", f->width, f->height, &pin))
			result = f->output;
	}
	f->display = result;
}

static void dob_render(void *data, gs_effect_t *unused)
{
	UNUSED_PARAMETER(unused);
	struct dob_filter *f = data;

	obs_source_t *target = obs_filter_get_target(f->context);
	obs_source_t *parent = obs_filter_get_parent(f->context);
	uint32_t w = target ? obs_source_get_base_width(target) : 0;
	uint32_t h = target ? obs_source_get_base_height(target) : 0;

	if (!f->effect || !target || !parent || !w || !h) {
		obs_source_skip_video_filter(f->context);
		return;
	}

	uint32_t fw = (w + f->downscale - 1) / f->downscale;
	uint32_t fh = (h + f->downscale - 1) / f->downscale;
	if (w != f->width || h != f->height || fw != f->flow_w || fh != f->flow_h) {
		f->width = w;
		f->height = h;
		f->flow_w = fw;
		f->flow_h = fh;
		f->have_prev = false;
		f->needs_update = true;
	}

	/* Advance exactly once per video frame: with look-ahead, processing the
	 * same frame twice would push a duplicate into the history. */
	if (f->needs_update) {
		gs_blend_state_push();
		gs_blend_function(GS_BLEND_ONE, GS_BLEND_ZERO);

		process_frame(f, target, parent);

		gs_blend_state_pop();
		f->needs_update = false;
	}

	gs_texture_t *tex = f->output_valid ? gs_texrender_get_texture(f->display) : NULL;
	if (!tex) {
		obs_source_skip_video_filter(f->context);
		return;
	}

	gs_effect_t *def = obs_get_base_effect(OBS_EFFECT_DEFAULT);
	gs_eparam_t *image = gs_effect_get_param_by_name(def, "image");
	gs_effect_set_texture(image, tex);

	gs_blend_state_push();
	gs_blend_function(GS_BLEND_ONE, GS_BLEND_INVSRCALPHA);
	while (gs_effect_loop(def, "Draw"))
		gs_draw_sprite(tex, 0, f->width, f->height);
	gs_blend_state_pop();
}

