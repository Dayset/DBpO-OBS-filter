enum clear_shape {
	CLEAR_OFF = 0,
	CLEAR_OVAL = 1,
	CLEAR_SQUARE = 2,
};

/* Look-ahead: output is delayed by up to this many frames so motion after
 * the output frame is known. Rings hold one slot per delayed frame + newest. */
#define MAX_LOOKAHEAD 6
#define RING_MAX (MAX_LOOKAHEAD + 1)
#define CAM_HIST 32

/* Grid the camera model is fitted on (read back to the CPU every frame). */
#define FIT_W 64
#define FIT_H 36

enum view_mode {
	VIEW_RESULT = 0,
	VIEW_VECTORS = 1,
	VIEW_CAMERA = 2,
	VIEW_OBJECTS = 3,
};

struct dob_filter {
	obs_source_t *context;
	gs_effect_t *effect;

	gs_texrender_t *frames[RING_MAX];   /* full-res source frames (ring, size lookahead+1) */
	gs_texrender_t *coh_ring[RING_MAX]; /* per-frame coherent motion (same ring) */
	int ring_size;
	uint64_t frame_no; /* frames processed since the last reset; newest = frame_no - 1 */
	uint64_t stage_frame[2];
	struct camera_model cam_hist[CAM_HIST];
	int64_t cam_hist_frame[CAM_HIST]; /* frame each cam_hist entry belongs to, -1 = empty */
	gs_texrender_t *small[2];         /* flow-res color, ping-pong current/previous */
	gs_texrender_t *flow;             /* raw block-matching motion */
	gs_texrender_t *fit;              /* FIT_W x FIT_H float32 motion for the camera fit */
	gs_stagesurf_t *stage[2];         /* readback ring, so the CPU never waits on this frame */
	int stage_idx;
	bool stage_ready[2];
	gs_texrender_t *combined; /* final motion: camera + object residual */
	gs_texrender_t *neighbor; /* neighbor-max motion */
	gs_texrender_t *output;   /* cached final frame */

	int cur; /* index into small[] holding the newest frame */
	bool have_prev;
	bool needs_update;
	bool output_valid;

	uint32_t width, height;
	uint32_t flow_w, flow_h;

	struct camera_model camera; /* smoothed camera motion, px/frame */

	/* settings */
	float strength; /* object blur strength */
	bool camera_enabled;
	float camera_strength;
	float camera_smoothing;
	float object_threshold;
	float max_radius;
	int downscale;
	int search_radius;
	float sensitivity;
	int coherence_radius;
	float min_motion;
	float static_bias;
	int samples;
	enum view_mode view;
	int lookahead;
	enum clear_shape clear_shape;
	float clear_size;    /* 0..1 */
	float clear_feather; /* 0..1 */
};

