static bool lookahead_modified(obs_properties_t *props, obs_property_t *p, obs_data_t *settings)
{
	UNUSED_PARAMETER(p);
	obs_property_t *info = obs_properties_get(props, S_LOOKAHEAD_INFO);
	if (!info)
		return false;

	int frames = (int)obs_data_get_int(settings, S_LOOKAHEAD);
	struct obs_video_info ovi;
	double fps = 60.0;
	if (obs_get_video_info(&ovi) && ovi.fps_den)
		fps = (double)ovi.fps_num / (double)ovi.fps_den;

	char text[256];
	if (frames <= 0)
		snprintf(text, sizeof(text), "%s", T("LookAheadInfo.Off"));
	else
		snprintf(text, sizeof(text), T("LookAheadInfo.On"), frames, 1000.0 * frames / fps, fps);
	obs_property_set_description(info, text);
	return true;
}

static void mouse_status_text(const struct dob_filter *f, char *buf, size_t size)
{
	if (!raw_mouse_supported()) {
		snprintf(buf, size, "%s", T("MouseStatus.Unsupported"));
	} else if (!f || !f->mouse_ref) {
		snprintf(buf, size, "%s", T("MouseStatus.Off"));
	} else if (!f->mouse_ok) {
		snprintf(buf, size, "%s: %s", T("MouseStatus.Error"), raw_mouse_status());
	} else if (!f->mouse_auto) {
		snprintf(buf, size, T("MouseStatus.Manual"), f->agree * 100.0f, f->sync.gain[0], f->sync.gain[1],
			 f->sync.lag, f->sync.correlation * 100.0f);
	} else if (!f->sync.ready) {
		snprintf(buf, size, T("MouseStatus.Learning"), f->sync.correlation * 100.0f);
	} else {
		snprintf(buf, size, T("MouseStatus.Ready"), f->sync.gain[0], f->sync.gain[1], f->sync.lag,
			 f->sync.correlation * 100.0f, f->agree * 100.0f);
	}
}

